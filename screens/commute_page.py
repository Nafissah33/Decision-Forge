"""Scenario A screen: Maya's commute. Logic lives in logic/commute_trajectory.py."""
from datetime import time
from pathlib import Path

import streamlit as st

import views
from logic.commute_trajectory import OPTIONS, evaluate_campus_route

DIAGRAMS = Path(__file__).resolve().parent.parent / "diagrams" / "campusroute_diagrams"
VARS = ["S", "F", "D", "W"]
DEFAULTS = {
    "bus": dict(dep=time(8, 0), travel=35, before=5, after=15, fare=3.0, rel=3),
    "train": dict(dep=time(8, 0), travel=25, before=5, after=5, fare=6.0, rel=5),
    "backup": dict(dep=time(8, 10), travel=25, before=0, after=5, fare=12.0, rel=4),
}


def show():
    st.header("🚌 Commute Assistant")
    st.caption("Maya must reach campus before her deadline. Enter the facts, then press Evaluate.")

    with st.form("commute"):
        c1, c2, c3, c4 = st.columns(4)
        deadline = c1.time_input("Arrival deadline", time(9, 0))
        budget = c2.number_input("Budget ($)", 0.0, value=10.0, step=0.5)
        weather = c3.selectbox("Weather", ["clear", "rain", "snow"])
        max_walk = c4.number_input("Max total walking (min)", 0, value=20)
        priority = st.segmented_control("Priority if several options qualify",
                                        ["earliest", "cheapest", "reliable"], default="earliest")
        opts = {}
        for tab, name in zip(st.tabs([n.title() for n in OPTIONS]), OPTIONS):
            d = DEFAULTS[name]
            with tab:
                a, b, c = st.columns(3)
                op = a.toggle("Service operating", True, key=f"{name}_op")
                dep = b.time_input("Departure", d["dep"], key=f"{name}_dep")
                fare = c.number_input("Fare ($)", 0.0, value=d["fare"], step=0.5, key=f"{name}_fare")
                a, b, c, e = st.columns(4)
                travel = a.number_input("Travel (min)", 0, value=d["travel"], key=f"{name}_tr")
                before = b.number_input("Walk before (min)", 0, value=d["before"], key=f"{name}_wb")
                after = c.number_input("Walk after (min)", 0, value=d["after"], key=f"{name}_wa")
                rel = e.slider("Reliability (1-5)", 1, 5, d["rel"], key=f"{name}_rel")
                opts[name] = {"operating": op, "departure": dep.strftime("%H:%M"), "fare": fare,
                              "travel_minutes": travel, "walk_before_minutes": before,
                              "walk_after_minutes": after, "reliability": rel}
        submitted = st.form_submit_button("Evaluate", type="primary")

    if submitted:
        try:
            st.session_state.commute_result = evaluate_campus_route({
                "deadline": deadline.strftime("%H:%M"), "budget": budget, "weather": weather,
                "priority": priority, "max_walk_minutes": max_walk, "options": opts})
        except ValueError as err:
            st.session_state.pop("commute_result", None)
            st.error(str(err))
    result = st.session_state.get("commute_result")
    if not result:
        return

    st.subheader("Recommendation")
    (st.success if result["recommended"] else st.warning)(result["summary"])

    st.subheader("Explanation")
    for name in OPTIONS:
        o = result["options"][name]
        st.markdown(f"{'✅' if o['eligible'] else '❌'} **{name.title()}**: {o['explanation']}")

    lines = ["DecisionForge - Commute Assistant summary", "", result["summary"], "",
             result["rule"], ""]
    lines += [f"{n.title()}: {'eligible' if result['options'][n]['eligible'] else 'not eligible'}"
              f" - {result['options'][n]['explanation']}" for n in OPTIONS]
    st.download_button("Download summary", "\n".join(lines), "commute_summary.txt")

    st.subheader("Logic views")
    pick = st.selectbox("Option to inspect", OPTIONS, format_func=str.title)
    o = result["options"][pick]
    t1, t2, t3, t4, t5 = st.tabs(["Truth table", "Expression tree", "Decision tree", "Knowledge graph", "Equivalence"])
    with t1:
        st.write(f"Rule: **{pick.title()}Eligible = S ∧ F ∧ D ∧ W**  "
                 "(S service, F fare in budget, D before deadline, W walking acceptable)")
        views.show_truth_table(VARS, "Eligible", o["propositions"])
    with t2:
        views.show_expression_tree(VARS)
    with t3:
        outcome = "Eligible" if o["eligible"] else "Not eligible"
        st.graphviz_chart(views.decision_tree_dot(o["decision_path"], outcome))
    with t4:
        st.graphviz_chart(views.knowledge_graph_dot(result["knowledge_graph_edges"]))
        views.show_adjacency(result["knowledge_graph_edges"])
    with t5:
        views.show_equivalence(VARS, f"{pick.title()}Eligible")

    with st.expander("Reference diagrams for the default example (by Nia)"):
        st.caption("Pre-generated by diagrams/campus_route_diagrams.py using the default "
                   "inputs. The tabs above update live with your inputs.")
        for title, name in (("Decision tree", "decision_tree"), ("Knowledge graph", "knowledge_graph")):
            img = DIAGRAMS / f"campusroute_{name}.png"
            if img.exists():
                st.image(str(img), caption=title)
